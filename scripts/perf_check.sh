#!/usr/bin/env bash
# Repeatable compile/runtime performance guard for Brook.
#
# Usage:
#   scripts/perf_check.sh record [baseline-file]   # measure and write baseline
#   scripts/perf_check.sh check  [baseline-file]   # measure and compare
#
# Environment overrides:
#   PERF_WARMUP=0.5 PERF_MEASUREMENT=2 PERF_SAMPLE_SIZE=30
#   PERF_WARN_RATIO=1.35 PERF_FAIL_RATIO=1.80
#   PERF_BASELINE_FILE=scripts/perf_baseline.env
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
export NO_COLOR=1

MODE="${1:-check}"
BASELINE_FILE="${2:-${PERF_BASELINE_FILE:-scripts/perf_baseline.env}}"
WARMUP="${PERF_WARMUP:-0.5}"
MEASUREMENT="${PERF_MEASUREMENT:-2}"
SAMPLE_SIZE="${PERF_SAMPLE_SIZE:-30}"
WARN_RATIO="${PERF_WARN_RATIO:-1.35}"
FAIL_RATIO="${PERF_FAIL_RATIO:-1.80}"

LOG_DIR="target/perf-check"
mkdir -p "$LOG_DIR"

# name|criterion filter
BENCHES=(
  "compile_fib|5_brook compile fib.bk"
  "vm_fib18|2_brook VM fib"
)

median_us_from() {
  awk '
    /time:/ && /\[/ {
      line = $0
      sub(/^.*\[/, "", line)
      sub(/\].*$/, "", line)
      n = split(line, a, /[ \t]+/)
      seen = 0
      for (i = 1; i <= n; i++) {
        if (a[i] ~ /^[0-9]+([.][0-9]+)?$/) {
          seen++
          if (seen == 2) {
            v = a[i] + 0
            u = tolower(a[i + 1])
            if (index(u, "µs") || index(u, "us")) { print v; exit }
            if (index(u, "ms")) { print v * 1000; exit }
            if (index(u, "ns")) { print v / 1000; exit }
            if (index(u, "s")) { print v * 1000000; exit }
          }
        }
      }
    }
  ' "$1"
}

run_bench() {
  local name="$1" filter="$2" log="$LOG_DIR/$name.txt"
  cargo bench --bench engine -- \
    --warm-up-time "$WARMUP" \
    --measurement-time "$MEASUREMENT" \
    --sample-size "$SAMPLE_SIZE" \
    "$filter" 2>&1 | tee "$log" >&2
  local us
  us="$(median_us_from "$log")"
  if [[ -z "$us" ]]; then
    echo "perf_check: cannot parse median from $log" >&2
    return 2
  fi
  printf '%s' "$us"
}

case "$MODE" in
  record)
    tmp="$BASELINE_FILE.tmp"
    {
      echo "# Generated by scripts/perf_check.sh; values are median microseconds."
      echo "BASELINE_DATE=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
      for spec in "${BENCHES[@]}"; do
        name="${spec%%|*}"
        filter="${spec#*|}"
        us="$(run_bench "$name" "$filter")"
        echo "BASELINE_${name}_US=$us"
      done
    } > "$tmp"
    mv "$tmp" "$BASELINE_FILE"
    echo "perf_check: baseline written to $BASELINE_FILE"
    ;;

  check)
    if [[ ! -f "$BASELINE_FILE" ]]; then
      echo "perf_check: missing baseline $BASELINE_FILE (run 'record' first)" >&2
      exit 2
    fi
    # shellcheck disable=SC1090
    source "$BASELINE_FILE"
    failed=0
    printf '%-16s %12s %12s %10s %s\n' BENCH BASELINE CURRENT RATIO STATUS
    for spec in "${BENCHES[@]}"; do
      name="${spec%%|*}"
      filter="${spec#*|}"
      key="BASELINE_${name}_US"
      base="${!key:-}"
      if [[ -z "$base" ]]; then
        echo "perf_check: missing $key in $BASELINE_FILE" >&2
        failed=2
        continue
      fi
      current="$(run_bench "$name" "$filter")"
      read -r ratio status < <(awk -v c="$current" -v b="$base" -v w="$WARN_RATIO" -v f="$FAIL_RATIO" '
        BEGIN {
          r = c / b
          if (r >= f) s = "FAIL"
          else if (r >= w) s = "WARN"
          else s = "OK"
          printf "%.3f %s\n", r, s
        }')
      printf '%-16s %12s %12s %10s %s\n' "$name" "$base" "$current" "$ratio" "$status"
      if [[ "$status" == "FAIL" ]]; then
        failed=1
      fi
    done
    exit "$failed"
    ;;

  *)
    echo "usage: $0 {record|check} [baseline-file]" >&2
    exit 2
    ;;
esac
